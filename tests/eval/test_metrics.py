"""Hand-computed metric values. Every expected number here is worked out by
hand in this file's comments, not generated by the code under test.
"""

import math

from braid.eval.metrics import RankedHit, _ties_broken, mrr, ndcg_at_k, recall_at_k


def hits(*ids: str) -> list[RankedHit]:
    """Ranked hits in the given order, rank = position (1-indexed)."""
    return [RankedHit(pid, i + 1) for i, pid in enumerate(ids)]


# ---- recall@k ----

def test_recall_at_k_single_relevant_below_cutoff():
    # relevant "a" is at rank 2; not in top-1, is in top-2 and top-3.
    ranked = hits("b", "a", "c")
    relevant = {"a": 1}
    assert recall_at_k(ranked, relevant, 1) == 0.0
    assert recall_at_k(ranked, relevant, 2) == 1.0
    assert recall_at_k(ranked, relevant, 3) == 1.0


def test_recall_at_k_multiple_relevant_partial():
    # relevant {a, b}; a at rank 1, b at rank 3 -> half found in top-2.
    ranked = hits("a", "c", "b")
    relevant = {"a": 1, "b": 1}
    assert recall_at_k(ranked, relevant, 1) == 0.5
    assert recall_at_k(ranked, relevant, 2) == 0.5
    assert recall_at_k(ranked, relevant, 3) == 1.0


def test_recall_at_k_no_relevant_found():
    ranked = hits("a", "b", "c")
    assert recall_at_k(ranked, {"z": 1}, 3) == 0.0


def test_recall_at_k_empty_relevant_is_vacuously_perfect():
    assert recall_at_k(hits("a", "b"), {}, 2) == 1.0


# ---- MRR ----

def test_mrr_first_relevant_at_rank_two():
    ranked = hits("b", "a", "c")
    assert mrr(ranked, {"a": 1}) == 0.5


def test_mrr_first_relevant_at_rank_one():
    ranked = hits("a", "c", "b")
    assert mrr(ranked, {"a": 1, "b": 1}) == 1.0


def test_mrr_no_relevant_found_is_zero():
    ranked = hits("a", "b", "c")
    assert mrr(ranked, {"z": 1}) == 0.0


# ---- nDCG@k ----

def test_ndcg_single_relevant_at_rank_two():
    # DCG = 1/log2(3) (gain 1 at rank 2); IDCG = 1/log2(2) = 1 (ideal: gain 1 at rank 1).
    ranked = hits("b", "a", "c")
    expected = (1 / math.log2(3)) / 1.0
    assert math.isclose(ndcg_at_k(ranked, {"a": 1}, 3), expected, rel_tol=1e-9)


def test_ndcg_two_relevant_multihop_style():
    # gains at ranks 1,2,3 = [1,0,1]; DCG = 1/log2(2) + 0 + 1/log2(4) = 1 + 0.5 = 1.5
    # IDCG (2 relevant, k=3): ideal gains [1,1] -> 1/log2(2) + 1/log2(3) = 1 + 0.630929...
    ranked = hits("a", "c", "b")
    relevant = {"a": 1, "b": 1}
    dcg = 1.0 + 0.5
    idcg = 1.0 + 1 / math.log2(3)
    expected = dcg / idcg
    assert math.isclose(ndcg_at_k(ranked, relevant, 3), expected, rel_tol=1e-9)
    assert math.isclose(expected, 0.9197, abs_tol=1e-4)


def test_ndcg_no_relevant_found_is_zero():
    ranked = hits("a", "b", "c")
    assert ndcg_at_k(ranked, {"z": 1}, 3) == 0.0


def test_ndcg_perfect_ranking_is_one():
    ranked = hits("a", "b", "c")
    relevant = {"a": 1, "b": 1}
    assert math.isclose(ndcg_at_k(ranked, relevant, 3), 1.0, rel_tol=1e-9)


def test_ndcg_empty_relevant_is_vacuously_perfect():
    assert ndcg_at_k(hits("a", "b"), {}, 2) == 1.0


def test_ndcg_ideal_capped_at_k():
    # 3 relevant passages but k=2: IDCG only accounts for 2 of them.
    ranked = hits("a", "b", "c")
    relevant = {"a": 1, "b": 1, "c": 1}
    idcg = 1.0 + 1 / math.log2(3)
    dcg = 1.0 + 1 / math.log2(3)  # both top-2 hits are relevant
    assert math.isclose(ndcg_at_k(ranked, relevant, 2), dcg / idcg, rel_tol=1e-9)
    assert math.isclose(ndcg_at_k(ranked, relevant, 2), 1.0, rel_tol=1e-9)


# ---- tie-breaking ----

def test_ties_broken_by_passage_id_ascending():
    tied = [RankedHit("zeta", rank=0, score=5.0), RankedHit("alpha", rank=0, score=5.0)]
    ordered = _ties_broken(tied)
    assert [h.passage_id for h in ordered] == ["alpha", "zeta"]
    assert [h.rank for h in ordered] == [1, 2]


def test_ties_broken_higher_score_wins_first():
    unordered = [RankedHit("a", rank=0, score=1.0), RankedHit("b", rank=0, score=9.0)]
    ordered = _ties_broken(unordered)
    assert [h.passage_id for h in ordered] == ["b", "a"]
